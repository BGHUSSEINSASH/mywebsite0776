/* tools/make-htaccess.js — the Apache half of the hosting story.
     node tools/make-htaccess.js [--host bghusseinsash.com] [--out .htaccess]

   firebase.json decides the headers on Firebase Hosting. this file decides
   the same headers on any Apache host — InfinityFree, a cPanel box, a VPS.
   both are rendered from tools/security-config.js, so the policy has one
   author and two renderings, and check-security.js fails the build the
   moment the two disagree.

   two things here are not optional decoration:

   · mod_rewrite. every internal link on this site is a clean url
     (/privacy, /work/bookly) and not one page links to a .html file, so
     without the rewrite below the site loads and then 404s on the first
     click. infinityfree documents mod_rewrite as enabled.

   · <IfModule>. a .htaccess line that names a directive Apache cannot find
     is a 500 on every page, not a warning. so each block is wrapped, and
     the worst case is a site with no headers from the server — the CSP
     <meta> tag on every page still holds the line, and only frame-ancestors
     and HSTS are lost, because a meta tag cannot carry those.

   --host pins an https redirect to one hostname. it is left out by default
   on purpose: forcing https before the certificate exists on the account
   turns a working site into an unreachable one. */

'use strict';

const fs = require('fs');
const path = require('path');
const { HEADERS, ADMIN_HEADERS } = require('./security-config');

const root = path.resolve(__dirname, '..');

function arg(name, fallback) {
  const i = process.argv.indexOf('--' + name);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const HOST = arg('host', '');
const OUT = path.resolve(root, arg('out', '.htaccess'));

if (HOST && !/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/i.test(HOST)) {
  console.error('refusing to write: --host ' + HOST + ' is not a hostname');
  process.exit(1);
}

/* a header value goes inside double quotes, so anything already quoted has
   to be escaped or it would close the string early and change the policy. */
function val(v) {
  return '"' + String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

function headerLines(map, indent) {
  return Object.keys(map)
    .map((k) => indent + 'Header always set ' + k + ' ' + val(map[k]))
    .join('\n');
}

/* the admin desk carries a different set: noindex, and no referrer at all.
   it is rendered as a delta over the general block, then the two keys that
   differ are stated in full, so nothing is inherited by accident. */
const ADMIN_ONLY = Object.keys(ADMIN_HEADERS).filter((k) => ADMIN_HEADERS[k] !== HEADERS[k]);
const ADMIN_SHARED = Object.keys(ADMIN_HEADERS).filter((k) => ADMIN_HEADERS[k] === HEADERS[k]);

const lines = [];

lines.push('# generated by tools/make-htaccess.js — do not edit by hand.');
lines.push('# the policy lives in tools/security-config.js; this is its Apache');
lines.push('# rendering, and check-security.js compares the two on every build.');
lines.push('');

if (HOST) {
  lines.push('<IfModule mod_rewrite.c>');
  lines.push('  RewriteEngine On');
  lines.push('  # the certificate has to exist on the account before this is switched on,');
  lines.push('  # which is why the generator only writes it when --host is given');
  lines.push('  RewriteCond %{HTTPS} off');
  lines.push('  RewriteCond %{HTTP_HOST} ^' + HOST.replace(/\./g, '\\.') + '$ [NC]');
  lines.push('  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]');
  lines.push('</IfModule>');
  lines.push('');
}

lines.push('<IfModule mod_rewrite.c>');
lines.push('  RewriteEngine On');
lines.push('');
lines.push('  # assets carry a ?v=rNN token and never change under it, so they are the');
lines.push('  # one thing on the site a browser may keep for a year');
lines.push('  RewriteRule ^assets/ - [E=BGSASH_IMMUTABLE:1]');
lines.push('');
lines.push('  # /index.html and /work/bookly.html are the same page as / and');
lines.push('  # /work/bookly, and two urls for one page is two entries in a search');
lines.push('  # index. the clean one wins.');
lines.push('  RewriteCond %{THE_REQUEST} \\s/+index\\.html[\\s?] [NC]');
lines.push('  RewriteRule ^ / [R=301,L]');
lines.push('  RewriteCond %{THE_REQUEST} \\s/+([^\\s?]+)\\.html[\\s?] [NC]');
lines.push('  RewriteRule ^ /%1 [R=301,L]');
lines.push('');
lines.push('  # …and the clean url has to find its file again. a real file or a real');
lines.push('  # directory is left alone, so /api/profile.json, /manifest.webmanifest');
lines.push('  # and /.well-known/security.txt all pass straight through.');
lines.push('  RewriteCond %{REQUEST_FILENAME} !-f');
lines.push('  RewriteCond %{REQUEST_FILENAME} !-d');
lines.push('  RewriteCond %{REQUEST_FILENAME}.html -f');
lines.push('  RewriteRule ^(.+?)/?$ $1.html [L]');
lines.push('</IfModule>');
lines.push('');

lines.push('# a miss answers with the real 404 page and a real 404 status — a soft');
lines.push('# 404 is a page that tells a search engine it exists');
lines.push('ErrorDocument 404 /404.html');
lines.push('');

lines.push('# chrome refuses a manifest it does not recognise, and not every Apache');
lines.push('# build ships these two types');
lines.push('<IfModule mod_mime.c>');
lines.push('  AddType application/manifest+json .webmanifest');
lines.push('  AddType font/woff2 .woff2');
lines.push('</IfModule>');
lines.push('');

lines.push('<IfModule mod_headers.c>');
lines.push('  # everything, everywhere');
lines.push(headerLines(HEADERS, '  '));
lines.push('');
lines.push('  # later directives win over earlier ones for the same header, so the');
lines.push('  # order below is the policy: re-validate everything, keep the assets');
lines.push('  # that carry a ?v=rNN token for a year, and never keep a page.');
lines.push('  Header always set Cache-Control "no-cache"');
lines.push('  Header always set Cache-Control "public, max-age=31536000, immutable" env=BGSASH_IMMUTABLE');
lines.push('  <FilesMatch "\\.(html|webmanifest)$">');
lines.push('    Header always set Cache-Control "no-cache, no-store, must-revalidate"');
lines.push('  </FilesMatch>');
lines.push('');
lines.push('  # the desk leaks nothing, not even a referrer. matched on the file, so');
lines.push('  # it covers /admin as well as /admin.html after the rewrite above.');
lines.push('  <FilesMatch "^admin\\.html$">');
lines.push(headerLines(ADMIN_ONLY.reduce((a, k) => ((a[k] = ADMIN_HEADERS[k]), a), {}), '    '));
lines.push('  </FilesMatch>');
lines.push('</IfModule>');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n') + '\n');

const shared = ADMIN_SHARED.length;
console.log('wrote ' + path.relative(root, OUT).replace(/\\/g, '/') + ' — ' + Object.keys(HEADERS).length + ' headers site-wide, ' +
  ADMIN_ONLY.length + ' overridden for admin (' + shared + ' inherited unchanged)' +
  (HOST ? ', https forced on ' + HOST : ', https redirect omitted (pass --host to add it)'));
